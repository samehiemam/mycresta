-- Configurator prices, moved off the client.
--
-- These figures used to live in app/configurator-data.ts, which meant they were
-- compiled into the JavaScript bundle every visitor downloads: the full Kumbra
-- price list was public, and the configurator's "hide prices" flag only ever
-- controlled whether the browser drew them. Hiding is not access control.
--
-- They now live here and are served by an endpoint that checks the session, so
-- a visitor who is not entitled to a price never receives one.
--
-- Keyed by the configurator's own option ids rather than the imported catalog's,
-- because the same id is legitimately priced differently per model — antifouling
-- is 3,200 on the 34 and 36 and 4,100 on the 43 — so model_key is part of the key.
--
-- Money in minor units, matching every other amount in this schema.
-- on_request marks an option that is offered but not priced; a missing row means
-- the option is not offered for that model at all. The two are different, and
-- collapsing them would quietly put unavailable equipment on a quotation.

CREATE TABLE IF NOT EXISTS configurator_prices (
  model_key   VARCHAR(8)  NOT NULL,
  -- base | engine | equipment
  item_kind   VARCHAR(12) NOT NULL,
  -- Empty for the hull itself, which has no option id.
  item_id     VARCHAR(64) NOT NULL DEFAULT '',
  price_minor BIGINT      NULL,
  on_request  TINYINT(1)  NOT NULL DEFAULT 0,
  currency    CHAR(3)     NOT NULL DEFAULT 'EUR',
  updated_by  CHAR(32)    NULL,
  updated_at  DATETIME    NOT NULL,
  PRIMARY KEY (model_key, item_kind, item_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

